"""生成 FuseSoC 2 `.core` 文档（只做文件列表/参数/target，不绑定 EDA 工具）。"""

from __future__ import annotations

from typing import Any

import yaml

from .emitter import CDC_MODULES
from .model import DesignModel


def _parameters(model: DesignModel) -> dict[str, dict[str, Any]]:
    parameters: dict[str, dict[str, Any]] = {}
    for module in model.modules:
        for param in module.params:
            if param.name in parameters:
                continue
            default = param.default
            datatype = "int" if isinstance(default, int) and not isinstance(default, bool) else "str"
            parameters[param.name] = {"datatype": datatype, "default": default}
    return parameters


def core_document(model: DesignModel) -> dict[str, Any]:
    files = [f"rtl/{module.name}.v" for module in model.modules]
    files.append(f"rtl/{model.project.top}.v")
    for kind in sorted({cdc.kind for cdc in model.cdc}):
        files.append(f"rtl/gen/cdc/{CDC_MODULES.get(kind, kind)}.v")

    document: dict[str, Any] = {
        "CAPI=2": 2,
        "name": f"rvgen:ip:{model.project.name}:1.0.0",
        "description": f"generated by rvgen from {model.source_name}",
        "filesets": {
            "rtl": {
                "files": files,
                "file_type": "verilogSource",
            }
        },
        "targets": {
            "default": {"filesets": ["rtl"]},
        },
    }
    parameters = _parameters(model)
    if parameters:
        document["parameters"] = parameters
    return document


def render_core(model: DesignModel) -> str:
    return yaml.safe_dump(core_document(model), sort_keys=False, allow_unicode=True)
